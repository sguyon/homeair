#!/usr/bin/env python3
"""Generate the demo's automatic roads and offline map data from a checked NYC release file.

No network: setup_roads receives the local release through the same GET boundary as household setup.
The clip keeps the selected roads' original keys, counts and measured slow hours.
"""
import argparse
import gzip
import hashlib
import io
import json
import os
import re
import sys
import tempfile
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import road_data
from roads import RoadFile, entry, find_roads
from build import clip_features, metro

ROOT = Path(__file__).resolve().parents[2]
GZIP_LEVEL = 9   # fixed compression level: Python's gzip defaults can change between versions


class LocalResponse:
    """The two local release files, in requests' streamed response shape."""
    status_code = 200

    def __init__(self, data):
        self.data = data

    def iter_content(self, size):
        yield self.data

    def close(self):
        pass


def generate(source: Path, sha256: str):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != sha256:
        raise ValueError("NYC source does not match the supplied sha256")
    doc = json.loads(gzip.decompress(raw))
    path = ROOT / "demo" / "config.toml"
    text = path.read_text(encoding="utf-8")
    # This comment belongs to the generator; setup preserves comments preceding its road blocks.
    text = re.sub(r"(?m)^# Automatic roads generated.*\n# Regenerate.*\n# python3 scripts/roads/demo.py.*\n", "", text)
    place = tomllib.loads(text)["place"]
    lat, lon = place["lat"], place["lon"]
    meta = {**metro("nyc"), "file": source.name, "sha256": sha256}
    index = json.dumps({"metros": [meta]}).encode()
    files = {"index.json": index, source.name: raw}
    with tempfile.TemporaryDirectory() as tmp:
        config_path = Path(tmp) / "config.toml"
        config_path.write_text(text, encoding="utf-8")
        # Prevent a caller's ROAD_DATA_DIR from writing into a real home's cache.
        old = os.environ.pop("ROAD_DATA_DIR", None)
        try:
            result = road_data.setup_roads(config_path, None,
                get=lambda url, **kw: LocalResponse(files[url.rsplit("/", 1)[-1]]))
        finally:
            if old is not None:
                os.environ["ROAD_DATA_DIR"] = old
        if result.status != "written":
            raise ValueError("; ".join(result.lines))
        generated = config_path.read_text(encoding="utf-8")
    entries = tomllib.loads(generated)["roads"]
    keys = {r["key"] for r in entries}
    features = clip_features(doc["features"], [(lat, lon)], road_data.ROUTE_CLIP_M)
    features = [f for f in features if f["properties"].get("g") in keys
                and not f["properties"].get("l") and not f["properties"].get("t")]
    clipped = {**doc, "roads": {k: v for k, v in doc["roads"].items() if k in keys}, "features": features}
    # The packaged geometry must generate exactly the same setup entries as the complete release.
    data = RoadFile(source.name, doc["country"], clipped["roads"], features)
    if [entry(r, source.name, data.country) for r in find_roads(lat, lon, data)] != entries:
        raise ValueError("The clip changes the demo's setup roads")
    # GzipFile writes the same OS byte across Python versions; no filename or timestamp enters the header.
    payload = json.dumps(clipped, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    output = io.BytesIO()
    with gzip.GzipFile(fileobj=output, mode="wb", filename="", compresslevel=GZIP_LEVEL, mtime=0) as stream:
        stream.write(payload)
    bundle = output.getvalue()
    folder = ROOT / "demo" / "road-data"
    folder.mkdir(exist_ok=True)
    (folder / source.name).write_bytes(bundle)
    manifest = {"file": source.name, "sha256": hashlib.sha256(bundle).hexdigest(),
                "source_sha256": sha256, "licence": doc["licence"], "credit": doc["credit"], "source": doc["source"]}
    (folder / "manifest.json").write_text(json.dumps(manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n", encoding="utf-8")
    comment = ("# Automatic roads generated by road_data.setup_roads; sorted JSON, fixed gzip header and level.\n"
               "# Regenerate (offline, from the repository root):\n"
               f"# python3 scripts/roads/demo.py /path/to/{source.name} --sha256 {sha256}\n")
    generated = generated.replace("[[roads]]", comment + "[[roads]]", 1)
    path.write_text(generated, encoding="utf-8")
    print(f"{len(entries)} automatic roads; offline clip: {len(bundle)} bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--sha256", required=True, help="trusted digest from the release index.json")
    args = parser.parse_args()
    generate(args.source, args.sha256)


if __name__ == "__main__":
    main()
